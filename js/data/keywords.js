/** 이름 → 항목 */
export const KEYWORD_MAP = new Map(KEYWORDS.map((k) => [k[0], { name: k[0], desc: k[1], cls: k[2] }]));

/** 긴 낱말부터 찾도록 정렬해 둔 목록 */
const SORTED = KEYWORDS.map((k) => k[0]).sort((a, b) => b.length - a.length);

/** 문장에 등장하는 키워드를 등장 순서대로 (중복 없이) 뽑아낸다 */
export function findKeywords(text) {
  if (!text) return [];
  const found = [];
  const taken = new Array(text.length).fill(false);
  SORTED.forEach((w) => {
    let i = text.indexOf(w);
    while (i >= 0) {
      let free = true;
      for (let k = i; k < i + w.length; k++) if (taken[k]) { free = false; break; }
      if (free) {
        for (let k = i; k < i + w.length; k++) taken[k] = true;
        found.push({ w, at: i });
        break;
      }
      i = text.indexOf(w, i + 1);
    }
  });
  return found.sort((a, b) => a.at - b.at).map((f) => KEYWORD_MAP.get(f.w));
}
